#!/usr/bin/env python3
"""Trace the sigil core and mote drawings into SVG paths for the sigil maker.

Usage: python3 tools/trace_sigils.py
Needs: pip install potracer pillow numpy

Reads assets/sigil-src/{core,mote}/*.png (512x512, black shape on transparent)
and writes src/tools/sigil/paths.generated.ts. Each path is in the image's
512x512 pixel space, to be drawn with fill-rule="evenodd".
"""
import json
import pathlib

import numpy as np
import potrace
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "sigil-src"
OUT = ROOT / "src" / "tools" / "sigil" / "paths.generated.ts"


def fmt(p):
    return "%g %g" % (round(p.x, 1), round(p.y, 1))


def trace(path):
    alpha = np.array(Image.open(path).convert("RGBA"))[:, :, 3] > 127
    # potracer traces the False pixels, so pass the inverse of the shape.
    curves = potrace.Bitmap(~alpha).trace(
        turdsize=4, alphamax=1.0, opticurve=True, opttolerance=0.2
    )
    d = []
    for c in curves:
        d.append("M" + fmt(c.start_point))
        for s in c.segments:
            if s.is_corner:
                d.append("L" + fmt(s.c) + "L" + fmt(s.end_point))
            else:
                d.append("C" + fmt(s.c1) + " " + fmt(s.c2) + " " + fmt(s.end_point))
        d.append("Z")
    return "".join(d)


def main():
    cores = {p.stem: trace(p) for p in sorted((SRC / "core").glob("*.png"))}
    motes = {p.stem: trace(p) for p in sorted((SRC / "mote").glob("*.png"))}
    OUT.write_text(
        "// Generated by tools/trace_sigils.py from assets/sigil-src. Do not edit.\n"
        "// Paths are in 512x512 pixel space; draw with fill-rule=\"evenodd\".\n\n"
        f"export const CORE_PATHS: Record<string, string> = {json.dumps(cores, indent=2)};\n\n"
        f"export const MOTE_PATHS: Record<string, string> = {json.dumps(motes, indent=2)};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(cores)} cores, {len(motes)} motes")


if __name__ == "__main__":
    main()
